#!/usr/bin/env python3
"""
Generate Report Tool

Generates a formatted markdown report from project analysis data.
"""

import json
from datetime import datetime
from pathlib import Path
from typing import Dict


def generate_report(
    project_data: str,
    output_mode: str = "display",
    output_file: str = ".project-context.md"
) -> str:
    """
    Generate formatted project context report.

    Args:
        project_data: JSON string containing all analysis data
        output_mode: "display" to return content, "save" to write file
        output_file: Filename to use if saving (default: .project-context.md)

    Returns:
        Report content (if display mode) or confirmation message (if save mode)
    """
    # Parse project data
    data = json.loads(project_data)

    # Generate markdown report
    report = _create_markdown_report(data)

    if output_mode == "save":
        # Write to file
        output_path = Path(output_file)
        with open(output_path, "w") as f:
            f.write(report)
        return f"✅ Report saved to {output_file}"
    else:
        # Return content for display
        return report


def _create_markdown_report(data: Dict) -> str:
    """Create the markdown report content."""
    framework = data.get("framework", {})
    dependencies = data.get("dependencies", {})
    structure = data.get("structure", {})
    entry_points = data.get("entry_points", {})

    # Build report sections
    sections = []

    # Header
    sections.append(_create_header(data, framework))

    # Tech Stack
    sections.append(_create_tech_stack_section(framework, dependencies))

    # Project Structure
    sections.append(_create_structure_section(structure))

    # Entry Points
    sections.append(_create_entry_points_section(entry_points))

    # Key Dependencies
    sections.append(_create_dependencies_section(dependencies))

    # Available Scripts
    if "scripts" in dependencies:
        sections.append(_create_scripts_section(dependencies["scripts"]))

    # Patterns Detected
    sections.append(_create_patterns_section(framework, dependencies, structure))

    # Development Workflow
    sections.append(_create_workflow_section(dependencies))

    # Footer
    sections.append("\n---\n*Generated by Project Context Analyzer*\n")

    return "\n\n".join(sections)


def _create_header(data: Dict, framework: Dict) -> str:
    """Create report header."""
    project_name = data.get("project_name", "Unknown Project")
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    framework_type = framework.get("type", "unknown")
    framework_name = framework.get("framework", "unknown")
    language = framework.get("language", "unknown")

    return f"""# Project Context: {project_name}

**Generated:** {timestamp}
**Type:** {framework_type.title()}
**Framework:** {framework_name.replace("-", " + ").title()}
**Language:** {language.title()}"""


def _create_tech_stack_section(framework: Dict, dependencies: Dict) -> str:
    """Create tech stack section."""
    lines = ["## Tech Stack\n"]

    # Runtime
    if framework.get("type") == "nodejs":
        node_version = dependencies.get("metadata", {}).get("node_version", "not specified")
        lines.append(f"- **Runtime:** Node.js ({node_version})")

    # Framework
    framework_name = framework.get("framework", "unknown")
    lines.append(f"- **Framework:** {framework_name.replace('-', ' + ').title()}")

    # Language
    language = framework.get("language", "unknown")
    lines.append(f"- **Language:** {language.title()}")

    # Key runtime dependencies
    runtime_deps = dependencies.get("runtime", [])
    if runtime_deps:
        key_deps = [f"{dep['name']} {dep['version']}" for dep in runtime_deps[:5]]
        lines.append(f"- **Key Dependencies:** {', '.join(key_deps)}")

    return "\n".join(lines)


def _create_structure_section(structure: Dict) -> str:
    """Create structure section."""
    lines = ["## Project Structure\n", "```"]

    # Source directories
    source = structure.get("source", {})
    if source:
        lines.append("src/")
        for path, info in list(source.items())[:10]:  # Limit to 10
            indent = "  " * path.count("/")
            dir_name = Path(path).name
            file_count = info.get("file_count", 0)
            lines.append(f"{indent}├── {dir_name}/ ({file_count} files)")

    # Tests
    tests = structure.get("tests", {})
    if tests:
        lines.append("tests/")
        for path in list(tests.keys())[:5]:
            lines.append(f"  ├── {Path(path).name}/")

    # Config files
    config = structure.get("config", [])
    if config:
        for cfg in config[:5]:
            lines.append(f"├── {Path(cfg).name}")

    lines.append("```")
    return "\n".join(lines)


def _create_entry_points_section(entry_points: Dict) -> str:
    """Create entry points section."""
    lines = ["## Entry Points\n"]

    main = entry_points.get("main", [])
    server = entry_points.get("server", [])
    framework_specific = entry_points.get("framework_specific", [])

    if main:
        lines.append(f"- **Main:** `{main[0]}`")

    if server:
        lines.append(f"- **Server:** `{server[0]}`")

    if framework_specific:
        for entry in framework_specific[:3]:
            lines.append(f"- **Framework:** `{entry}`")

    if not (main or server or framework_specific):
        lines.append("- No entry points detected")

    return "\n".join(lines)


def _create_dependencies_section(dependencies: Dict) -> str:
    """Create dependencies section."""
    lines = ["## Key Dependencies\n"]

    runtime = dependencies.get("runtime", [])

    if runtime:
        # Group by category (heuristic)
        for dep in runtime[:10]:  # Show top 10
            name = dep["name"]
            version = dep["version"]
            lines.append(f"- **{name}** ({version})")

    total = dependencies.get("total_count", 0)
    if total:
        lines.append(f"\n*Total: {total} dependencies*")

    return "\n".join(lines)


def _create_scripts_section(scripts: Dict) -> str:
    """Create scripts section."""
    lines = ["## Available Scripts\n"]

    important_scripts = ["dev", "start", "build", "test", "lint", "format"]

    for script_name in important_scripts:
        if script_name in scripts:
            lines.append(f"- `{script_name}` - {scripts[script_name]}")

    # Show other scripts
    other_scripts = [s for s in scripts.keys() if s not in important_scripts]
    if other_scripts:
        lines.append(f"\n*{len(other_scripts)} additional scripts available*")

    return "\n".join(lines)


def _create_patterns_section(framework: Dict, dependencies: Dict, structure: Dict) -> str:
    """Create patterns detected section."""
    lines = ["## Patterns Detected\n"]

    patterns = []

    # Framework patterns
    framework_name = framework.get("framework", "")
    if "react" in framework_name:
        patterns.append("Component-based architecture (React)")
    if "next" in framework_name:
        patterns.append("Server-side rendering / Static generation")
    if "express" in framework_name or "fastify" in framework_name:
        patterns.append("REST API architecture")

    # Language patterns
    if framework.get("language") == "typescript":
        patterns.append("TypeScript for type safety")

    # Testing patterns
    runtime_deps = {d["name"] for d in dependencies.get("runtime", [])}
    dev_deps = {d["name"] for d in dependencies.get("dev", [])}
    all_deps = runtime_deps | dev_deps

    if "vitest" in all_deps:
        patterns.append("Vitest for testing")
    elif "jest" in all_deps:
        patterns.append("Jest for testing")

    if "@testing-library/react" in all_deps:
        patterns.append("React Testing Library")

    # Styling patterns
    if "tailwindcss" in all_deps:
        patterns.append("Tailwind CSS for styling")
    elif "styled-components" in all_deps:
        patterns.append("Styled Components (CSS-in-JS)")

    # Show patterns
    for pattern in patterns:
        lines.append(f"- {pattern}")

    if not patterns:
        lines.append("- No specific patterns detected")

    return "\n".join(lines)


def _create_workflow_section(dependencies: Dict) -> str:
    """Create development workflow section."""
    lines = ["## Development Workflow\n"]

    scripts = dependencies.get("scripts", {})

    if "dev" in scripts or "start" in scripts:
        dev_cmd = "dev" if "dev" in scripts else "start"
        lines.append(f"1. **Start development:** `npm run {dev_cmd}`")

    if "test" in scripts:
        lines.append("2. **Run tests:** `npm test`")

    if "build" in scripts:
        lines.append("3. **Build for production:** `npm run build`")

    if not scripts:
        lines.append("- No workflow scripts detected")

    return "\n".join(lines)


if __name__ == "__main__":
    import sys

    # Read project data from stdin or file
    if len(sys.argv) > 1:
        with open(sys.argv[1]) as f:
            project_data = f.read()
    else:
        project_data = sys.stdin.read()

    output_mode = sys.argv[2] if len(sys.argv) > 2 else "display"
    output_file = sys.argv[3] if len(sys.argv) > 3 else ".project-context.md"

    # Generate report
    result = generate_report(project_data, output_mode, output_file)
    print(result)
